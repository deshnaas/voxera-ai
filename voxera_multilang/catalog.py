def say(key: str, lang: str) -> str:
    entry = PH[key]
    return entry.get(lang) or entry["en"]


def triage_question(key: str, lang: str, english: str) -> str:
    return TRIAGE_Q.get(key, {}).get(lang) or english


def triage_conclusion(name: str, lang: str, english: str) -> str:
    return TRIAGE_CONCLUSION.get(name, {}).get(lang) or english


def emergency_text(spoken_english: str, lang: str) -> str:
    """Localized version of one of the frozen detector's canned replies (English if unknown / lang == en)."""
    if lang == "en":
        return spoken_english
    try:
        import voxera_emergency as em
    except Exception:                                   # noqa: BLE001
        return spoken_english
    for name, per in EMERGENCY.items():
        if getattr(em, name, None) == spoken_english:
            return per.get(lang) or spoken_english
    return EMERGENCY["_R_GENERAL"][lang]                 # unknown line: the generic, always-safe one


def care_reply(care, otc, profile: dict, lang: str, with_help: bool = True, with_caveat: bool = True) -> Optional[str]:
    """Localized curated guidance for a care topic (first step + OTC line + when to get help), no LLM."""
    block = CARE.get(care.care_id)
    if lang == "en" or not block:
        return None
    parts = [block["step"][lang]]
    if otc is not None:
        if otc.deferred:
            parts.append(OTC_CHILD_DEFER[lang])
        elif otc.items:
            item = OTC.get(otc.items[0])
            if item:
                child = profile.get("is_child") or (profile.get("age") or 99) < 12
                if child and item.get("child"):
                    parts.append(item["child"][lang])
                else:
                    parts.append(item["adult"][lang])
                    if with_caveat and item.get("caveat", {}).get(lang):
                        parts.append(item["caveat"][lang])
                    if profile.get("pregnant"):
                        parts.append(OTC_PREGNANT[lang])
    if with_help:
        parts.append(f"{say('care_help_if', lang)} {block['help'][lang]}।" if lang == "hi" else f"{say('care_help_if', lang)} {block['help'][lang]}.")
    return " ".join(p.strip() for p in parts if p)
